"""The research index: every study folder, its status and one-line verdict.

    uv run python -m horizon_trader.results.index          # rewrite research/README.md
    uv run python -m horizon_trader.results.index --check  # exit 1 if invalid or stale

The format (one folder per study):

    research/<slug>/
        README.md      the write-up, verdict in the first paragraph
        result.json    id, name, kind, status, verdict, tags, updated, period, artifacts
        protocol.md    optional: the rules, written before the results
        *.csv / *.py   small evidence and the scripts that made it; big data stays in data/

A study may hold sub-studies (folders with their own result.json), e.g. research/orb_ema/*.
"""

from __future__ import annotations

import sys
from pathlib import Path

from horizon_trader import config
from horizon_trader.results.catalog import STATUSES, Result, load_manifest

# Folders under research/ that are inputs to code, not studies of their own.
NOT_STUDIES: set[str] = set()

HEADINGS = {
    "core": "Core: trading or forward-testing now",
    "candidate": "Candidates: passed tests, not yet trading",
    "running": "Running forward tests",
    "inconclusive": "Inconclusive",
    "idea": "Ideas and plans",
    "reference": "Reference notes and diagnostics",
    "dead": "Dead: tested and rejected",
}


def studies(repo: Path | None = None) -> tuple[list[Result], list[str]]:
    """Every research manifest plus a list of format problems (missing fields, files)."""
    repo = (repo or config.REPO_ROOT).resolve()
    root = repo / "research"
    found, problems = [], []
    for folder in sorted(p for p in root.iterdir() if p.is_dir()):
        if folder.name in NOT_STUDIES or folder.name.startswith((".", "_")):
            continue
        if not (folder / "result.json").is_file():
            problems.append(f"research/{folder.name}: no result.json")
    loose = sorted(p.name for p in root.glob("*.md") if p.name != "README.md")
    problems += [f"research/{name}: notes go in research/<slug>/README.md" for name in loose]
    for path in sorted(root.rglob("result.json")):
        rel = path.parent.relative_to(root).as_posix()
        try:
            result = load_manifest(path, config.data_dir())
        except (OSError, ValueError, TypeError, KeyError) as exc:
            problems.append(f"research/{rel}/result.json: {exc}")
            continue
        for key in ["status", "verdict"]:
            if not result.metadata.get(key):
                problems.append(f"research/{rel}/result.json: missing {key}")
        if result.report is None:
            problems.append(f"research/{rel}: no README.md")
        found.append(result)
    return found, problems


def _cell(text: str) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def render(found: list[Result], root: Path) -> str:
    lines = [
        "# Research index",
        "",
        "Generated by `uv run python -m horizon_trader.results.index` from each study's",
        "`result.json`. Edit those (and the study's README.md), not this file.",
        "",
        "Each study is a folder: `README.md` (verdict first), `result.json` (status, verdict,",
        "tags, period, artifacts), an optional `protocol.md` written before the results, and",
        "small evidence files. Large data stays under `data/` and is referenced as `data:...`.",
        "",
    ]
    counts = {s: sum(r.status == s for r in found) for s in STATUSES}
    lines.append(" · ".join(f"**{counts[s]}** {s}" for s in STATUSES if counts[s]))
    for status in STATUSES:
        group = [r for r in found if r.status == status]
        if not group:
            continue
        lines += ["", f"## {HEADINGS[status]}", "", "| Study | Verdict | Period | Tags |"]
        lines.append("|---|---|---|---|")
        for r in sorted(group, key=lambda r: r.source.parent.relative_to(root).as_posix()):
            rel = r.source.parent.relative_to(root).as_posix()
            report = r.report.relative_to(root).as_posix() if r.report else f"{rel}/"
            period = f"{r.start[:7]} to {r.end[:7]}" if r.start and r.end else ""
            lines.append(
                f"| [{_cell(r.name)}]({report}) | {_cell(r.verdict)} | {period} | "
                f"{', '.join(r.tags)} |"
            )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    root = config.REPO_ROOT / "research"
    found, problems = studies()
    for problem in problems:
        print("PROBLEM", problem)
    text = render(found, root)
    target = root / "README.md"
    if "--check" in argv:
        stale = not target.exists() or target.read_text(encoding="utf-8") != text
        if stale:
            print("research/README.md is stale: run python -m horizon_trader.results.index")
        return 1 if problems or stale else 0
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {target} ({len(found)} studies)")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
